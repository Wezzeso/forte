def test_host_timeout_removes_only_its_unique_helper(tmp_path, monkeypatch, capsys):
    root = tmp_path / "ops"
    root.mkdir()
    for name in ("population.json", "runtime.json", "worker.json", "comparison.json"):
        write_new(root / name, {})
    monkeypatch.setattr(host, "inspect", lambda name: {"Image": "sha256:" + "a" * 64})
    commands = []
    def launch(command, **kwargs):
        commands.append(command)
        if command[:2] == ["docker", "run"]:
            raise host.subprocess.TimeoutExpired(command, 120)
        return SimpleNamespace(returncode=0, stdout=b"", stderr=b"")
    monkeypatch.setattr(host.subprocess, "run", launch)
    assert host.main(["bind", "--ops-root", str(root), "--population", "population.json",
        "--runtime-config", "runtime.json", "--worker-recipe", "worker.json", "--comparison-plan", "comparison.json",
        "--bound-root", "bound", "--arm", "qwen38_tuned"]) == 1
    name = commands[0][commands[0].index("--name") + 1]
    assert name.startswith("forte-acceptance-ops-")
    assert commands[1] == ["docker", "rm", "--force", name]
    assert "forte-api-1" not in commands[1] and "forte-worker-1" not in commands[1]


def test_operational_bundle_includes_local_nonproduction_imports():
    root = Path(ops.__file__).resolve().parents[2]
    bundle = set(ops.BUNDLE_CODE)
    for relative in bundle:
        module = root / relative
        assert module.is_file()
        for node in ast.walk(ast.parse(module.read_text(encoding="utf-8"))):
            if isinstance(node, ast.ImportFrom) and node.module and not node.level:
                if node.module.startswith(("training.", "scripts.", "benchmarks.", "evaluation.")):
                    dependency = node.module.replace(".", "/") + ".py"
                    if (root / dependency).is_file():
                        assert dependency in bundle, f"{relative} needs {dependency}"
